import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, within } from '@testing-library/react'
import { App } from './App'
import { canvasContextPrototype } from './canvas-context.test-support'
import { uiText } from './i18n'
import { clickSheet, clickTemplateFrame, templateColumnHeaderPoint, templateFramePoint, setSheetRect, enterTimingValue, expectSelectedHit, expectSelectedRange } from './App.test-support'

beforeEach(() => {
  vi.spyOn(canvasContextPrototype(), 'getContext').mockReturnValue(null)
  localStorage.removeItem('xsheet:timing-input-circles')
})
afterEach(() => { vi.restoreAllMocks(); localStorage.removeItem('xsheet:timing-input-circles') })

function setup() {
  render(<App />)
  const sheet = screen.getByLabelText(uiText.sheet.canvasLabel)
  setSheetRect(sheet, 0, 0)
  const menu = (role: 'action' | 'cell', frame: number) => {
    const point = templateFramePoint(role, 'A', frame)
    fireEvent.contextMenu(sheet, { clientX: point.x, clientY: point.y })
  }
  return { sheet, menu }
}
const cell = (role: 'action' | 'cell', frame: number) => document.querySelector(`[data-timeline-event-role="${role}"][data-timeline-event-track="A"][data-timeline-event-frame="${frame}"]`)
const ghost = (track: string, frame: number) => document.querySelector(`[data-transfer-track="${track}"][data-transfer-frame="${frame}"]`)
const openTransfer = () => fireEvent.click(screen.getByRole('menuitem', { name: 'ACTION→CELLに自動採番して転記…' }))

it('checks separate input-circle options, preserves triangles and transfers enclosed drawings atomically', () => {
  const { sheet, menu } = setup()
  menu('action', 1)
  expect(screen.getByRole('menuitemcheckbox', { name: '記入時に○を付ける' }).getAttribute('aria-checked')).toBe('false')
  fireEvent.click(screen.getByRole('menuitemcheckbox', { name: '記入時に○を付ける' }))
  menu('action', 1)
  expect(screen.getByRole('menuitemcheckbox', { name: /記入時に○を付ける/ }).getAttribute('aria-checked')).toBe('true')
  fireEvent.keyDown(window, { key: 'Escape' })
  clickTemplateFrame(sheet, 'action', 'A', 1)
  enterTimingValue('1')
  fireEvent.keyDown(window, { key: '/', code: 'Slash' })
  enterTimingValue('2')
  menu('action', 4)
  fireEvent.click(screen.getByRole('menuitem', { name: '参考記号を付加（△）' }))
  clickTemplateFrame(sheet, 'action', 'A', 4)
  enterTimingValue('あ')
  expect(cell('action', 1)?.querySelector('circle.eventReferenceSymbol')).toBeTruthy()
  expect(cell('action', 3)?.querySelector('circle.eventReferenceSymbol')).toBeTruthy()
  expect(cell('action', 4)?.querySelector('polygon.eventReferenceSymbol')).toBeTruthy()
  expect(cell('action', 4)?.querySelector('circle.eventReferenceSymbol')).toBeNull()
  const registered = document.querySelectorAll('.cspTreeCel[data-csp-key-id]:not(.unregistered)').length
  menu('cell', 1)
  expect(screen.getByRole('menuitemcheckbox', { name: '記入時に○を付ける' }).getAttribute('aria-checked')).toBe('false')
  openTransfer()
  const preview = screen.getByRole('region', { name: 'ACTION→CELLの転記プレビュー' })
  expect([1, 2, 3, 4].map(frame => ghost('A', frame)?.querySelector('.eventText')?.textContent)).toEqual(['1', '2', '3', '4'])
  expect(ghost('A', 1)?.querySelector('circle')).toBeTruthy()
  expect(ghost('A', 4)?.querySelector('polygon')).toBeTruthy()
  expect(cell('cell', 1)).toBeNull()
  expect(document.querySelectorAll('.cspTreeCel[data-csp-key-id].unregistered')).toHaveLength(0)
  clickTemplateFrame(sheet, 'action', 'A', 1)
  enterTimingValue('9')
  expect(cell('action', 1)?.querySelector('.eventText')?.textContent).toBe('1')
  fireEvent.click(within(preview).getByRole('button', { name: 'キャンセル' }))
  expect(ghost('A', 1)).toBeNull()
  expect(cell('cell', 1)).toBeNull()
  menu('cell', 1)
  openTransfer()
  fireEvent.click(screen.getByRole('button', { name: 'OK' }))
  expect(screen.queryByRole('region', { name: 'ACTION→CELLの転記プレビュー' })).toBeNull()
  expect([1, 2, 3, 4].map(frame => cell('cell', frame)?.querySelector('.eventText')?.textContent)).toEqual(['1', '2', '3', '4'])
  expect(cell('cell', 1)?.querySelector('circle.eventReferenceSymbol')).toBeTruthy()
  expect(cell('cell', 3)?.querySelector('circle.eventReferenceSymbol')).toBeTruthy()
  expect(cell('cell', 4)?.querySelector('polygon.eventReferenceSymbol')).toBeTruthy()
  expect(document.querySelectorAll('.cspTreeCel[data-csp-key-id]:not(.unregistered)')).toHaveLength(registered)
  expect(document.querySelectorAll('.cspTreeCel[data-csp-key-id].unregistered')).toHaveLength(4)
  fireEvent.click(screen.getByRole('button', { name: uiText.actions.undo }))
  expect(cell('cell', 1)).toBeNull()
  expect(document.querySelectorAll('.cspTreeCel[data-csp-key-id].unregistered')).toHaveLength(0)
  expect(cell('action', 1)?.querySelector('circle.eventReferenceSymbol')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: uiText.actions.redo }))
  expect(cell('cell', 3)?.querySelector('.eventText')?.textContent).toBe('3')
  menu('cell', 1)
  openTransfer()
  expect((screen.getByRole('button', { name: 'OK' }) as HTMLButtonElement).disabled).toBe(true)
})

it('defaults to all ACTION columns for no selection, a cell or partial range, and restricts only a whole-column selection', () => {
  const { sheet, menu } = setup()
  clickTemplateFrame(sheet, 'action', 'A', 1); enterTimingValue('10')
  clickTemplateFrame(sheet, 'action', 'B', 1); enterTimingValue('20')
  const expectAll = () => {
    menu('action', 1); openTransfer()
    expect(ghost('A', 1)?.textContent).toContain('1')
    expect(ghost('B', 1)?.textContent).toContain('1')
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(ghost('A', 1)).toBeNull()
    expect(cell('cell', 1)).toBeNull()
  }
  fireEvent.keyDown(window, { key: 'Escape' })
  expectAll()
  clickTemplateFrame(sheet, 'action', 'A', 1)
  expectAll()
  clickTemplateFrame(sheet, 'action', 'A', 1)
  fireEvent.keyDown(window, { key: 'ArrowDown', shiftKey: true })
  expectAll()
  const header = templateColumnHeaderPoint('action', 'A')
  clickSheet(sheet, header.x, header.y)
  menu('action', 1); openTransfer()
  expect(ghost('A', 1)?.textContent).toContain('1')
  expect(ghost('B', 1)).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'OK' }))
  expect(cell('cell', 1)?.querySelector('.eventText')?.textContent).toBe('1')
  expect(document.querySelector('[data-timeline-event-role="cell"][data-timeline-event-track="B"]')).toBeNull()
})

it('previews lip-sync numbers and reverse inbetweens in numeric order, then applies and undoes together', () => {
  const { sheet, menu } = setup()
  clickTemplateFrame(sheet, 'action', 'A', 1)
  for (const value of ['3', '2', '3', '1']) enterTimingValue(value)
  clickTemplateFrame(sheet, 'action', 'B', 1)
  enterTimingValue('2'); fireEvent.keyDown(window, { key: '/', code: 'Slash' })
  enterTimingValue('1'); fireEvent.keyDown(window, { key: '/', code: 'Slash' }); enterTimingValue('2')
  menu('action', 1); openTransfer()
  expect([1, 2, 3, 4].map(frame => ghost('A', frame)?.querySelector('.eventText')?.textContent)).toEqual(['3', '2', '3', '1'])
  expect([1, 2, 3, 4, 5].map(frame => ghost('B', frame)?.querySelector('.eventText')?.textContent)).toEqual(['3', '2', '1', '2', '3'])
  expect(cell('cell', 1)).toBeNull()
  expect(screen.queryByText('採番についての確認事項')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'OK' }))
  expect(cell('cell', 1)?.querySelector('.eventText')?.textContent).toBe('3')
  expect(cell('action', 1)?.querySelector('.eventText')?.textContent).toBe('3')
  fireEvent.click(screen.getByRole('button', { name: uiText.actions.undo }))
  expect(document.querySelectorAll('[data-timeline-event-role="cell"]')).toHaveLength(0)
  fireEvent.click(screen.getByRole('button', { name: uiText.actions.redo }))
  expect(cell('cell', 4)?.querySelector('.eventText')?.textContent).toBe('1')
})

it('explains additional numbering in the ghost preview without blocking confirmation or mutating on cancel', () => {
  const { sheet, menu } = setup()
  clickTemplateFrame(sheet, 'action', 'A', 1)
  for (const value of ['1', '/', '2', 'x', '1', '/', '/', '2']) {
    if (value === '/') fireEvent.keyDown(window, { key: '/', code: 'Slash' })
    else enterTimingValue(value)
  }
  menu('action', 1); openTransfer()
  expect(screen.getByText('採番についての確認事項')).toBeTruthy()
  expect(screen.getByText(/A：2、6、7コマの絵は、原画番号の間へ一意に並べられない/)).toBeTruthy()
  expect((screen.getByRole('button', { name: 'OK' }) as HTMLButtonElement).disabled).toBe(false)
  expect(ghost('A', 3)?.querySelector('.eventText')?.textContent).toBe('2')
  expect(ghost('A', 6)?.querySelector('.eventText')?.textContent).toBe('4')
  fireEvent.click(screen.getByRole('button', { name: 'キャンセル' }))
  expect(ghost('A', 1)).toBeNull()
  expect(cell('cell', 1)).toBeNull()
})

it('accepts main/numpad ticks in one press with stepped selection, while respecting drafts and composition', () => {
  const { sheet } = setup()
  clickTemplateFrame(sheet, 'action', 'A', 1)
  for (const code of ['Slash', 'NumpadDivide']) fireEvent.keyDown(window, { key: '/', code })
  expectSelectedHit('action', 'A', 3)
  fireEvent.keyDown(window, { key: '/', code: 'Slash', repeat: true })
  expectSelectedHit('action', 'A', 3)
  fireEvent.keyDown(window, { key: '.', code: 'NumpadDecimal', isComposing: true })
  fireEvent.keyDown(window, { key: '/', keyCode: 229 })
  expect(cell('action', 3)).toBeNull()
  fireEvent.keyDown(window, { key: '.', code: 'Period' })
  fireEvent.keyDown(window, { key: ',', code: 'NumpadDecimal' })
  expectSelectedHit('action', 'A', 5)
  enterTimingValue('1/2.3')
  expect(cell('action', 5)?.querySelector('.eventText')?.textContent).toBe('1/2.3')
  fireEvent.keyDown(window, { key: 'ArrowDown', shiftKey: true })
  fireEvent.keyDown(window, { key: 'ArrowDown', shiftKey: true })
  expectSelectedRange('action', 'A', 6, 8)
  fireEvent.keyDown(window, { key: '/', code: 'NumpadDivide' })
  expectSelectedRange('action', 'A', 9, 11)
  expect(cell('action', 6)?.querySelector('.eventInbetweenSymbol')).toBeTruthy()
  expect(cell('action', 7)).toBeNull()
  fireEvent.keyDown(window, { key: 'Delete', code: 'NumpadDecimal' })
  expect(cell('action', 9)).toBeNull()
})
