const clipChapterIds = ['assets', 'project', 'cut', 'io', 'shortcuts']

export function EditorDetailedHelp({ topic, ...selection }: { topic: 'sheet' | 'clip' } & HelpChapterSelection) {
  const selected = topic === 'clip'
    ? clipChapterIds.flatMap(id => editorHelpChapters.filter(chapter => chapter.id === id))
    : editorHelpChapters.filter(chapter => chapter.id !== 'assets')
  const chapters = selected.map((chapter, index) => ({ ...chapter, number: String(index + 1).padStart(2, '0') }))
  return <ChapteredHelp chapters={chapters} idPrefix={`remap-help-${topic}`} {...selection} />
}
