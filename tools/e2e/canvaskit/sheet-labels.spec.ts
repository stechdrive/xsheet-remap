import { readFileSync } from 'node:fs'
import { expect, test } from './fixtures'
import { activateControl } from './input'
import { activeCutProjectFromDocument, buildClipRegistrationPlan, createDefaultProject, createKey, createProjectDocumentFromCutProject, setEvent, upsertBinding } from '../../../packages/core/src/index'
import { decodeProjectFileBytes, encodeProjectArchive } from '../../../packages/adapters/src/projectArchive'
import { waitForPaperPaint } from '../paper-paint-contract'

test('fits long sheet labels, previews sheet-only rename, and preserves timing and CSP names through undo/save', async ({ page }, info) => {
  const first = createKey(createDefaultProject(), 'A', '0001', 'import', '0001', 'action')
  let project = setEvent(first.project, 'A', 1, first.key.keyId, 'action', { fontSizePx: 72 })
  project = setEvent(project, 'A', 5, first.key.keyId, 'action')
  project = upsertBinding(project, { slotId: 'slot_A', keyId: first.key.keyId, cspCellName: '0001', materialState: 'unassigned' })
  const longName = '123456789012345678901234567890'
  const long = createKey(project, 'B', longName, 'import', longName, 'action')
  project = setEvent(long.project, 'B', 1, long.key.keyId, 'action')
  project = upsertBinding(project, { slotId: 'slot_B', keyId: long.key.keyId, cspCellName: longName, materialState: 'unassigned' })
  const document = createProjectDocumentFromCutProject(project)
  const archive = Buffer.from(await encodeProjectArchive(document))
  // Exercise the legacy binding cards in Editor; Remap uses the CLIP layer tree.
  await page.goto('./?app=editor')
  await activateControl(page, page.getByLabel('画面切替', { exact: true }))
  await page.getByRole('button', { name: 'プロジェクトを開く…', exact: true }).setInputFiles({ name: 'long-labels.xsr', mimeType: 'application/octet-stream', buffer: archive })
  const svg = page.locator('.sheetSvg').first()
  await expect(svg).toHaveAttribute('data-canvaskit-state', 'active', { timeout: 40_000 })
  await page.evaluate(() => document.fonts.ready)
  await waitForPaperPaint({ evaluate: <T>(expression: string) => page.evaluate<T>(expression) })
  const event = (track: string, frame: number) => page.locator(`[data-timeline-event-role="action"][data-timeline-event-track="${track}"][data-timeline-event-frame="${frame}"]`)
  const text = (track: string, frame: number) => event(track, frame).locator('.eventText')
  await expect(text('A', 1)).toHaveText('0001')
  await expect(text('B', 1)).toHaveAttribute('data-text-overflow', 'true')
  await expect(text('B', 1)).toHaveAttribute('aria-label', longName)
  await expect(text('B', 1)).toContainText('…')
  const bounds = await event('A', 1).evaluate(element => {
    const cell = element.querySelector('.eventRect')!.getBoundingClientRect()
    const text = element.querySelector('.eventText')!.getBoundingClientRect()
    return { cell: cell.toJSON(), text: text.toJSON() }
  })
  expect(bounds.text.left).toBeGreaterThanOrEqual(bounds.cell.left - .1)
  expect(bounds.text.right).toBeLessThanOrEqual(bounds.cell.right + .1)
  const point = await event('B', 1).locator('.eventRect').boundingBox()
  expect(point).not.toBeNull()
  if (info.project.name.endsWith('-touch')) await page.touchscreen.tap(point!.x + point!.width / 2, point!.y + point!.height / 2)
  else await page.mouse.click(point!.x + point!.width / 2, point!.y + point!.height / 2)
  await expect(page.locator('.timingCellFullLabel')).toContainText(longName)
  await page.screenshot({ path: info.outputPath('fitted-labels.png') })
  const rename = page.getByRole('button', { name: '一括リネーム', exact: true })
  if (!await rename.isVisible()) await activateControl(page, page.getByRole('button', { name: 'CSPレイヤー構成', exact: true }))
  await activateControl(page, rename)
  await page.getByRole('combobox', { name: '変更する名前', exact: true }).selectOption('sheet')
  const dialog = page.getByRole('dialog', { name: 'シート記載を一括変更' })
  await expect(dialog.getByText('シート記載 1件', { exact: true })).toBeVisible()
  const geometry = await dialog.locator('.nameNormalizationDialog').boundingBox()
  expect(geometry!.x).toBeGreaterThanOrEqual(0)
  expect(geometry!.x + geometry!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('rename-preview.png') })
  await activateControl(page, dialog.getByRole('button', { name: 'この内容でシート記載を変更' }))
  await expect(dialog).toHaveCount(0)
  await expect(text('A', 1)).toHaveText('1')
  await expect(text('A', 5)).toHaveText('1')
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(text('A', 1)).toHaveText('0001')
  await activateControl(page, page.getByRole('button', { name: 'やり直し', exact: true }))
  await expect(text('A', 1)).toHaveText('1')
  const card = page.locator(`.cspTreeCel[data-csp-key-id="${first.key.keyId}"]`)
  const sheetLabel = card.locator('.cspTreeSheetLabel')
  await expect(sheetLabel).toHaveText('シート: 1')
  await sheetLabel.press('Enter')
  const input = card.getByRole('textbox', { name: 'Aのシート表記', exact: true })
  await input.fill('仮001')
  await input.press('Escape')
  await expect(sheetLabel).toHaveText('シート: 1')
  await sheetLabel.press('Enter')
  await input.fill('12')
  const inputBox = await input.boundingBox(), cardBox = await card.boundingBox()
  expect(inputBox!.width).toBeGreaterThan(30)
  expect(inputBox!.x + inputBox!.width).toBeLessThanOrEqual(cardBox!.x + cardBox!.width)
  await page.screenshot({ path: info.outputPath('sheet-label-edit.png') })
  await input.press('Enter')
  await expect(text('A', 1)).toHaveText('12')
  await expect(text('A', 5)).toHaveText('12')
  await expect(card.locator('.cspTreeCelName')).toHaveText('0001')
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(text('A', 1)).toHaveText('1')
  await activateControl(page, page.getByRole('button', { name: 'やり直し', exact: true }))
  await expect(text('A', 1)).toHaveText('12')
  await activateControl(page, page.getByLabel('画面切替', { exact: true }))
  await activateControl(page, page.getByRole('button', { name: 'プロジェクト ›', exact: true }))
  const download = page.waitForEvent('download')
  await activateControl(page, page.getByRole('button', { name: '名前を付けて保存…', exact: true }))
  const saved = info.outputPath('renamed.xsr')
  await (await download).saveAs(saved)
  const reopened = (await decodeProjectFileBytes(new Uint8Array(readFileSync(saved)))).document
  const next = activeCutProjectFromDocument(reopened)
  expect(next.bindings).toEqual(project.bindings)
  expect(next.logicalSheet.events).toEqual(project.logicalSheet.events)
  expect(next.logicalSheet.keys.find(key => key.keyId === first.key.keyId)?.displayLabel).toBe('12')
  expect(buildClipRegistrationPlan(reopened, 'action')).toEqual(buildClipRegistrationPlan(document, 'action'))
})
