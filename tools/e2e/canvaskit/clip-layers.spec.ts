test('CLIP palette colors and media import retain timing and link SOUND with one undo', async ({ page, browserName }, info) => {
  const require = createRequire(import.meta.url)
  const SQL = await initSqlJs({ wasmBinary: new Uint8Array(readFileSync(require.resolve('sql.js/dist/sql-wasm.wasm'))).buffer })
  const { clip } = createMediaFixture(SQL), bytes = Buffer.from(clip.bytes()); clip.close()
  await page.goto('./?app=remap')
  await activateControl(page, page.getByRole('button', { name: 'CLIP組み立て', exact: true }))
  await expect(page.locator('.sheetSvg').first()).toHaveAttribute('data-canvaskit-state', 'active', { timeout: 40_000 })
  await activateControl(page, page.getByLabel('画面切替', { exact: true }))
  await activateControl(page, page.getByRole('button', { name: '読み込み ›', exact: true }))
  await page.locator('input[type=file][accept=".clip"]').setInputFiles({ name: 'media.clip', mimeType: 'application/octet-stream', buffer: bytes })
  const dialog = page.getByRole('dialog', { name: 'CLIPを読み込む', exact: true })
  await expect(dialog.getByRole('button', { name: 'すべて解除', exact: true })).toBeVisible()
  await activateControl(page, dialog.getByRole('button', { name: 'すべて解除', exact: true }))
  await activateControl(page, dialog.getByRole('button', { name: 'タイムシートに読み込む', exact: true }))
  const movie = row(page, 'probe-video')
  await expect(movie).toContainText('動画')
  await expect(movie.locator('.clipLayerEye')).toHaveCSS('background-color', 'rgb(255, 170, 130)')
  await activateControl(page, page.getByRole('button', { name: 'probe-videoをクイックルック', exact: true }))
  await expect(page.locator('.clipLayerNotice')).toContainText('この動画レイヤーには保存済み画像がありません')
  await expect(page.getByRole('dialog', { name: 'probe-videoのプレビュー', exact: true })).toHaveCount(0)
  await activateControl(page, row(page, 'probe-audio'))
  const opacity = page.getByRole('slider', { name: 'レイヤーの不透明度スライダー', exact: true })
  await expect(opacity).toBeDisabled()
  await expect(row(page, 'probe-audio').locator('.clipLayerEye')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await activateControl(page, page.getByRole('button', { name: 'セリフ音声へ取り込む', exact: true }))
  if (process.platform === 'win32' && browserName === 'webkit') {
    // The Windows Playwright WebKit build omits Web Audio. Verify the unavailable path without a mock decoder.
    expect(await page.evaluate(() => typeof AudioContext)).toBe('undefined')
    await expect(page.locator('.clipAudioImport')).toContainText('この環境では音声をデコードできません')
    await expect(page.locator('.soundCue')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'セリフ音声へ取り込む', exact: true })).toBeEnabled()
    return
  }
  await expect(page.locator('.clipAudioImport')).toContainText('1個の音声クリップを取り込みました。', { timeout: 15_000 })
  await expect(page.locator('.soundCue').first()).toHaveAttribute('aria-label', 'probe-audio 1-72')
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(page.locator('.soundCue')).toHaveCount(0)
  await activateControl(page, page.getByRole('button', { name: 'やり直し', exact: true }))
  await expect(page.locator('.soundCue').first()).toHaveAttribute('aria-label', 'probe-audio 1-72')
  await activateControl(page, page.getByRole('button', { name: 'セリフ音声へ取り込む', exact: true }))
  await expect(page.locator('.clipAudioImport')).toContainText('取り込み済み')
  const geometry = await page.locator('.clipLayerPanel').evaluate(element => ({ overflow: element.scrollWidth > element.clientWidth, treeHeight: element.querySelector('.clipLayerTree')!.clientHeight }))
  expect(geometry.overflow).toBe(false); expect(geometry.treeHeight).toBeGreaterThan(100)
  await page.screenshot({ path: info.outputPath('clip-media-sound.png') })
})
async function cell(page: Page, frame: number) {
  const rect = cellRectForHit(standardA3SheetTemplate, timingHitForFrame(standardA3SheetTemplate, 'cell', 'A', frame)!)!
  return page.locator('.sheetSvg').first().evaluate((element, r) => {
    const box = element.getBoundingClientRect()
    return { x: box.x + (r.x + r.w / 2) * box.width, y: box.y + (r.y + r.h / 2) * box.height }
  }, rect)
}

test('two-pane layer workspace imports, previews, reuses cels, filters without changing exposure and exports static materials', async ({ page }, info) => {
  await page.goto('./?app=remap')
  await activateControl(page, page.getByRole('button', { name: 'CLIP組み立て', exact: true }))
  await expect(page.locator('.sheetSvg').first()).toHaveAttribute('data-canvaskit-state', 'active', { timeout: 40_000 })
  await expect(page.locator('#sheet-left-pane')).toHaveCount(0)
  await expect(page.locator('#sheet-right-pane .clipLayerPanel')).toBeVisible()
  const tree = page.getByRole('tree', { name: 'CLIPレイヤーツリー' })
  const pane = page.locator('.clipLayerPanel')
  await activateControl(page, page.locator('[data-clip-layer-id="slot:slot_A"]'))
  const process = await page.getByLabel('新規画像の登録先', { exact: true }).inputValue()
  await pane.locator('input[type=file]').setInputFiles([image('001.png'), image('002.png')])
  await expect(row(page, '002')).toBeVisible()
  await expect(page.locator('.eventText')).toHaveCount(0)
  await activateControl(page, page.getByRole('button', { name: '001をクイックルック', exact: true }))
  const preview = page.getByRole('dialog', { name: '001のプレビュー', exact: true })
  await expect(preview.locator('img')).toBeVisible()
  expect(await preview.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1)
  await activateControl(page, page.getByRole('button', { name: 'プレビューを閉じる', exact: true }))
  const event = (frame: number) => page.locator(`[data-timeline-event-role="cell"][data-timeline-event-track="A"][data-timeline-event-frame="${frame}"] .eventText`)
  async function drag(frame: number, cancel = false) {
    await row(page, '001').evaluate(element => element.scrollIntoView({ block: 'nearest' }))
    const from = await row(page, '001').boundingBox(), to = await cell(page, frame)
    expect(to.x).toBeLessThan(page.viewportSize()!.width)
    expect(to.y).toBeLessThan(page.viewportSize()!.height)
    await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
    await page.mouse.down()
    await page.mouse.move(to.x, to.y, { steps: 8 })
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
  }
  await drag(1, true)
  await expect(event(1)).toHaveCount(0)
  await drag(1)
  await expect(event(1)).toHaveText('1')
  await drag(7)
  await expect(event(7)).toHaveText('1')
  await expect(row(page, '001')).toHaveCount(1)
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(event(7)).toHaveCount(0)
  await expect(row(page, '001')).toHaveCount(1)
  await activateControl(page, page.getByRole('button', { name: 'やり直し', exact: true }))
  await page.getByLabel('登録先工程の素材だけ表示', { exact: true }).check()
  const other = await page.getByLabel('新規画像の登録先', { exact: true }).locator('option').evaluateAll((options, current) => (options as HTMLOptionElement[]).find(option => option.value !== current)!.value, process)
  await page.getByLabel('新規画像の登録先', { exact: true }).selectOption(other)
  await expect(event(1)).toHaveCount(0)
  await page.getByLabel('新規画像の登録先', { exact: true }).selectOption(process)
  await expect(event(1)).toHaveText('1')
  await expect(event(7)).toHaveText('1')
  const box = await tree.boundingBox()
  expect(box!.width).toBeGreaterThan(170)
  expect(box!.x).toBeGreaterThan(page.viewportSize()!.width / 2)
  expect(box!.height).toBeGreaterThan(150)
  await page.screenshot({ path: info.outputPath('clip-layer-workspace.png') })

  // The tree background denotes the document root, independently of the selected cel.
  const transfer = await page.evaluateHandle(base64 => {
    const transfer = new DataTransfer()
    transfer.items.add(new File([Uint8Array.from(atob(base64), char => char.charCodeAt(0))], 'BOOK.png', { type: 'image/png' }))
    return transfer
  }, png.toString('base64'))
  await pane.dispatchEvent('drop', { dataTransfer: transfer })
  await transfer.dispose()
  await expect(row(page, 'BOOK')).toBeAttached()
  await activateControl(page, row(page, 'BOOK'))
  await activateControl(page, page.getByLabel('レイヤーメニュー', { exact: true }))
  await expect(page.getByLabel('レイヤーの移動先', { exact: true })).toHaveValue('')
  await activateControl(page, page.getByLabel('レイヤーメニュー', { exact: true }))
  await activateControl(page, page.getByText('シートとの対応を設定', { exact: true }))
  await activateControl(page, page.getByRole('button', { name: 'BOOK表示＋', exact: true }))
  await expect(row(page, 'BOOK')).toContainText('旗')

  await activateControl(page, page.getByLabel('画面切替', { exact: true }))
  await activateControl(page, page.getByRole('button', { name: '書き出し ›', exact: true }))
  await activateControl(page, page.getByRole('button', { name: 'CLIPを作成…', exact: true }))
  const dialog = page.getByRole('dialog', { name: 'CLIPを作成', exact: true })
  await dialog.getByLabel('作画サイズ（用紙サイズ） 幅（px）', { exact: true }).fill('32')
  await dialog.getByLabel('作画サイズ（用紙サイズ） 高さ（px）', { exact: true }).fill('24')
  await dialog.getByLabel('基準サイズ（撮影フレーム） 幅（px）', { exact: true }).fill('24')
  await dialog.getByLabel('基準サイズ（撮影フレーム） 高さ（px）', { exact: true }).fill('16')
  await activateControl(page, dialog.getByRole('button', { name: 'CELL', exact: true }))
  const download = page.waitForEvent('download')
  await activateControl(page, dialog.getByRole('button', { name: 'CLIPを作成して保存…', exact: true }))
  const saved = info.outputPath('tree.clip')
  await (await download).saveAs(saved)
  const require = createRequire(import.meta.url)
  const SQL = await initSqlJs({ wasmBinary: new Uint8Array(readFileSync(require.resolve('sql.js/dist/sql-wasm.wasm'))).buffer })
  const data = await readClip(SQL, new Uint8Array(readFileSync(saved)), 'tree.clip')
  expect(data.layers!.find(node => node.name === 'BOOK')).toMatchObject({ kind: 'raster', parentId: null })
  const cel = data.layers!.find(node => node.name === '001')!
  expect(data.timelines[0].tracks.find(track => track.layerId === cel.parentId)?.frames).toEqual([{ frame: 0, value: '001' }, { frame: 6, value: '001' }])
  expect(data.layers!.filter(node => node.name === 'BOOK')).toHaveLength(1)
})

test('right layer palette properties, insertion feedback and history agree', async ({ page }, info) => {
  await page.goto('./?app=remap')
  await activateControl(page, page.getByRole('button', { name: 'CLIP組み立て', exact: true }))
  await expect(page.locator('.sheetSvg').first()).toHaveAttribute('data-canvaskit-state', 'active', { timeout: 40_000 })
  const pane = page.locator('.clipLayerPanel')
  await activateControl(page, page.locator('[data-clip-layer-id="slot:slot_A"]'))
  await pane.locator('input[type=file]').setInputFiles([image('001.png'), image('002.png'), image('003.png')])
  await expect(row(page, '003')).toBeAttached()
  await activateControl(page, row(page, '001').locator('.clipLayerName'))
  await page.getByLabel('レイヤーの不透明度', { exact: true }).fill('35')
  await page.getByLabel('レイヤーの不透明度', { exact: true }).press('Enter')
  await expect(row(page, '001')).toContainText('35%')
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(row(page, '001')).toContainText('100%')
  await activateControl(page, page.getByRole('button', { name: 'やり直し', exact: true }))
  await page.getByLabel('レイヤーの合成モード', { exact: true }).selectOption('2')
  await expect(row(page, '001')).toContainText('35% 乗算')
  await activateControl(page, row(page, '001').getByRole('checkbox', { name: '001の表示' }))
  await expect(row(page, '001').getByRole('checkbox')).not.toBeChecked()
  await expect(row(page, '001')).toContainText('35% 乗算')

  const order = () => page.locator('[data-clip-layer-id="slot:slot_A"]').locator('..').locator(':scope > [role=group] > [role=treeitem] > .clipLayerRow .clipLayerName')
  await row(page, '003').evaluate(element => element.scrollIntoView({ block: 'nearest' }))
  async function move(cancel: boolean) {
    const from = (await row(page, '003').locator('.clipLayerThumbnail').boundingBox())!, to = (await row(page, '001').boundingBox())!
    await page.mouse.move(from.x + from.width * .8, from.y + from.height / 2)
    await page.mouse.down()
    await page.mouse.move(to.x + to.width * .8, to.y + 3, { steps: 8 })
    await expect(row(page, '001').locator('..')).toHaveClass(/clipDropBefore/)
    await expect(pane.locator('.clipDropStatus')).toHaveText('001 の上に挿入')
    if (cancel) {
      await page.screenshot({ path: info.outputPath('insertion-preview.png') })
      await page.keyboard.press('Escape')
    }
    await page.mouse.up()
  }
  await move(true)
  await expect(order()).toHaveText(['001', '002', '003'])
  await expect(pane.locator('.clipDropBefore')).toHaveCount(0)
  await move(false)
  await expect(order()).toHaveText(['003', '001', '002'])
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(order()).toHaveText(['001', '002', '003'])

  const transfer = await page.evaluateHandle(base64 => {
    const transfer = new DataTransfer()
    transfer.items.add(new File([Uint8Array.from(atob(base64), char => char.charCodeAt(0))], 'insert.png', { type: 'image/png' }))
    return transfer
  }, png.toString('base64'))
  const destination = (await row(page, '002').boundingBox())!
  await row(page, '002').dispatchEvent('dragover', { dataTransfer: transfer, clientX: destination.x + 120, clientY: destination.y + 3 })
  await expect(row(page, '002').locator('..')).toHaveClass(/clipDropBefore/)
  await row(page, '002').dispatchEvent('drop', { dataTransfer: transfer, clientX: destination.x + 120, clientY: destination.y + 3 })
  await transfer.dispose()
  await expect(row(page, 'insert')).toBeAttached()
  await expect(order()).toHaveText(['001', 'insert', '002', '003'])
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(order()).toHaveText(['001', '002', '003'])

  await activateControl(page, row(page, '001').locator('.clipLayerName'))
  await activateControl(page, page.getByRole('button', { name: '新規ラスターレイヤー', exact: true }))
  await expect(row(page, 'レイヤー')).toBeAttached()
  page.once('dialog', dialog => dialog.accept())
  await activateControl(page, page.getByRole('button', { name: 'レイヤーを削除', exact: true }))
  await expect(row(page, 'レイヤー')).toHaveCount(0)
  await activateControl(page, page.getByRole('button', { name: '元に戻す', exact: true }))
  await expect(row(page, 'レイヤー')).toBeAttached()
  await row(page, '001').locator('.clipLayerName').dblclick()
  await page.getByLabel('レイヤー名', { exact: true }).fill('001_原画')
  await page.getByLabel('レイヤー名', { exact: true }).press('Enter')
  await expect(row(page, '001_原画')).toContainText('35% 乗算')
  const geometry = await pane.evaluate(element => ({ width: element.clientWidth, overflow: element.scrollWidth > element.clientWidth, treeHeight: element.querySelector('.clipLayerTree')!.clientHeight }))
  expect(geometry.overflow).toBe(false)
  expect(geometry.treeHeight).toBeGreaterThan(150)
  await page.screenshot({ path: info.outputPath('palette-properties.png') })
})
