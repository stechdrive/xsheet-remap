import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(scriptDirectory, '..', '..')
const sourcePath = path.join(repoRoot, 'packages', 'core', 'src', 'after-effects-template.jsx')
const generatedPath = path.join(repoRoot, 'packages', 'core', 'src', 'after-effects-template.generated.ts')
const marker = '// xsheet-remap After Effects remap JSX v1'
const placeholder = '__XSHEET_AE_CONFIG__'
const checkOnly = process.argv.includes('--check')

const template = normalizeLineEndings(await readFile(sourcePath, 'utf8'))
validateTemplate(template)
const expected = renderGeneratedModule(template)
const current = await readOptionalFile(generatedPath)

if (checkOnly) {
  if (current === null || normalizeLineEndings(current) !== expected) {
    console.error('[ae-template] generated TypeScript module is stale; run npm run sync:ae-template')
    process.exitCode = 1
  } else {
    console.log('[ae-template] generated TypeScript module is current')
  }
} else if (current !== null && normalizeLineEndings(current) === expected) {
  console.log('[ae-template] generated TypeScript module is already current')
} else {
  await writeFile(generatedPath, expected, 'utf8')
  console.log(`[ae-template] wrote ${path.relative(repoRoot, generatedPath).replace(/\\/g, '/')}`)
}

function renderGeneratedModule(source) {
  const literal = JSON.stringify(source)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
  return [
    '// This file is generated by tools/after-effects/sync-template.mjs.',
    '// Edit after-effects-template.jsx, then run npm run sync:ae-template.',
    '',
    `const AFTER_EFFECTS_TEMPLATE = ${literal}`,
    '',
    'export default AFTER_EFFECTS_TEMPLATE',
    '',
  ].join('\n')
}

function validateTemplate(source) {
  if (!source.split('\n').slice(0, 4).includes(marker)) {
    throw new Error(`After Effects template must contain ${marker} within its first four lines`)
  }
  if (source.split(placeholder).length !== 2) {
    throw new Error('After Effects template must contain exactly one XSHEET config placeholder')
  }
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/g, '\n')
}

async function readOptionalFile(filePath) {
  try {
    return await readFile(filePath, 'utf8')
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return null
    throw error
  }
}
