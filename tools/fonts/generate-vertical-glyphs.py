"""Extract LINE Seed JP's OpenType vert outlines; no font is modified.

Generator only: pip install fonttools==4.67.0 brotli==1.2.0
Run from repository root. The application has no Python dependency.
"""
import hashlib
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'node_modules/@fontsource/line-seed-jp'
OUTPUT = ROOT / 'packages/ui/src/verticalGlyphData.ts'


def number(value):
    return f'{value:.5f}'.rstrip('0').rstrip('.') or '0'


def generate():
    result = {}
    digest = hashlib.sha256()
    for weight in (400, 700, 800):
        glyphs = {}
        for path in sorted((SOURCE / 'files').glob(f'line-seed-jp-*-{weight}-normal.woff2')):
            if '-japanese-' in path.name:
                continue
            digest.update(path.name.encode())
            digest.update(path.read_bytes())
            font = TTFont(path)
            if 'GSUB' not in font:
                continue
            table = font['GSUB'].table
            substitutions = []
            for record in table.FeatureList.FeatureRecord:
                if record.FeatureTag != 'vert':
                    continue
                for index in record.Feature.LookupListIndex:
                    for subtable in table.LookupList.Lookup[index].SubTable:
                        subtable = getattr(subtable, 'ExtSubTable', subtable)
                        if hasattr(subtable, 'mapping'):
                            substitutions.append(subtable.mapping)
            glyph_set = font.getGlyphSet()
            units = font['head'].unitsPerEm
            for code, original in font.getBestCmap().items():
                alternate = original
                for mapping in substitutions:
                    alternate = mapping.get(alternate, alternate)
                if alternate == original:
                    continue
                pen = SVGPathPen(glyph_set, ntos=number)
                glyph_set[alternate].draw(TransformPen(pen, (1 / units, 0, 0, -1 / units, 0, 0)))
                glyphs[chr(code)] = {'path': pen.getCommands(), 'advance': font['hmtx'].metrics[alternate][0] / units}
            font.close()
        result[str(weight)] = dict(sorted(glyphs.items()))
    header = '// Generated by tools/fonts/generate-vertical-glyphs.py. Do not edit.\n'
    header += '// LINE Seed JP outlines: Copyright LY Corporation, SIL OFL 1.1.\n'
    header += f'// Source @fontsource/line-seed-jp {json.loads((SOURCE / "package.json").read_text())["version"]}; SHA-256 {digest.hexdigest()}\n'
    header += 'export const verticalGlyphData: Record<string, Record<string, { path: string; advance: number }>> = '
    OUTPUT.write_text(header + json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print({key: len(value) for key, value in result.items()}, OUTPUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    generate()
